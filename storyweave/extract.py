"""用文本模型通读原文，抽出人物卡、场景卡、风格 ID 与故事节拍草稿。

抽取的输入是原文文本本身：本模块把原文全文拼进提示，交给注入的模型调用函数
（提示 -> 文本），再把模型返回的结构化结果解析、校验成草稿。
模型调用由调用方注入，本模块不绑定任何供应商，也不访问网络。
人物、服装、场景、情节顺序和未支持判定出自同一趟通读；未支持判定按人物给出，
无从归属的线索记为无主线索（见 DEC-7，正则规则表只作提示，见 storyweave.unsupported）。
草稿是纯数据：不写页图、不写参考图、不写 PDF。出页粒度分两种：未处理的无主线索拦整篇
（整篇可出页），未跳过的未支持条目只拦该人物（人物可出页），两者都现算，不落快照键。
正式入口是 抽取短篇草稿（先验 1 万到 2 万字）；抽取草稿 不验篇幅，供评测节选直接调用。
"""

from __future__ import annotations

import json
from typing import Any, Callable, Mapping

from storyweave.unsupported import 未支持类别, 构建未支持提示

最少字数 = 10000
最多字数 = 20000
未确认 = "未确认"
人物身份字段 = ("脸型", "发型与发色", "眼", "显著特征", "年龄", "体态")

模型调用 = Callable[[str], str]

抽取提示模板 = """你是短篇漫画的设定抽取员。通读下面这篇短篇的原文全文，一趟抽出人物卡、\
场景卡、一个风格 ID 和故事节拍，并按人物给出未支持判定。

要求：
1. 输入就是原文本身，不要假设任何外部给定的结构化结果。
2. 只输出一个 JSON 对象：不要解释，不要 Markdown 代码围栏，不要多余文字。
3. JSON 结构如下（字段名照抄，六项身份字段都要出现，原文没给的写空字符串）：
{结构}
4. 人物身份六项写同一人物不随镜头改变的样貌事实：脸型、发型与发色、眼（眼型与瞳色）、\
显著特征、年龄、体态。服装状态挂在人物下，不要写进身份。人物卡名称必须唯一，同一人物只建一张卡。
5. 故事节拍每条都要带原文位置，位置用原文的字符下标（第 1 个字是 0）；人物、服装、\
场景的原文起止同样用字符下标。
6. 未支持判定按人物给出：该人物发生年龄阶段切换、伪装成他人或变身时，在「未支持」里记一条，\
类别只能取 变身 / 伪装成他人 / 年龄阶段切换；没有就给空列表。普通换装、正常长一岁、只改发型\
这类不算；开玩笑式的扮相（扮成鬼脸、扮成圣诞老人）不算。
7. 未支持状态下，人物身份字段只保留进入该状态之前的样貌。原文没有给出进入该状态之前的样貌时，\
六项全部留空，不得用变身后的描述填充；不要另存一份变身后的样貌，也不要因此放弃这个人物的其他字段。
8. 无从归属到任何人物卡的未支持线索记进「无主线索」：不要为它新建人物卡，也不要写进任何人物卡。
9. 场景卡记名称、建筑外观和原文位置；风格 ID 只给一个；此步不产出页图，也不产出参考图。

字样提示：
{字样提示}

原文全文如下：
<<<原文
{原文}
原文>>>
"""

结构模板 = """{
  "人物": [
    {
      "名称": "人物在原文里的称呼，必须唯一",
      "身份": {"脸型": "", "发型与发色": "", "眼": "", "显著特征": "", "年龄": "", "体态": ""},
      "原文起": 0,
      "原文止": 0,
      "服装": [{"名称": "", "描述": "", "原文起": 0, "原文止": 0}],
      "未支持": [{"类别": "变身", "片段": ""}]
    }
  ],
  "场景": [{"名称": "", "建筑外观": "", "原文起": 0, "原文止": 0}],
  "风格ID": "",
  "故事节拍": [{"顺序": 1, "摘要": "", "原文起": 0, "原文止": 0}],
  "无主线索": [{"类别": "变身", "片段": ""}]
}"""


class 篇幅不符(ValueError):
    """原文去掉空白后的字数不在 10000 到 20000 之间。"""

    def __init__(self, 字数: int):
        self.字数 = 字数
        super().__init__(f"短篇字数须在 {最少字数} 到 {最多字数} 之间，当前为 {字数}")


class 模型输出不可解析(ValueError):
    """模型返回的文本不是一个 JSON 对象。"""


class 草稿非法(ValueError):
    """模型返回的结构化结果不符合契约要求。"""


class 名称重复(草稿非法):
    """两张人物卡用了同一个名称。"""


def 计字(原文: str) -> int:
    if not isinstance(原文, str):
        raise TypeError("原文必须是字符串")
    return sum(1 for 字 in 原文 if not 字.isspace())


def 校验篇幅(原文: str) -> None:
    """正式路径的篇幅门槛：短篇须在 1 万到 2 万字之间。

    评测样本是原文节选，不受这个门槛约束，所以抽取本身不调用它。
    """
    字数 = 计字(原文)
    if 字数 < 最少字数 or 字数 > 最多字数:
        raise 篇幅不符(字数)


def 构建抽取提示(原文: str) -> str:
    """把原文全文拼成抽取提示：输入是原文本身，模型按契约字段返回结构化草稿。"""
    if not isinstance(原文, str):
        raise TypeError("原文必须是字符串")
    return 抽取提示模板.format(结构=结构模板, 字样提示=构建未支持提示(原文), 原文=原文)


def 解析模型输出(文本: str) -> dict[str, Any]:
    """把模型返回的文本解析成映射：允许整段带 ```json 围栏，必须是一个 JSON 对象。"""
    if not isinstance(文本, str):
        raise 模型输出不可解析("模型返回的必须是字符串")
    try:
        值 = json.loads(_去代码围栏(文本))
    except json.JSONDecodeError as 错:
        raise 模型输出不可解析(f"模型返回的不是合法 JSON：{错}") from 错
    if not isinstance(值, dict):
        raise 模型输出不可解析("模型返回的 JSON 必须是一个对象")
    return 值


def 抽取草稿(原文: str, 调用模型: 模型调用) -> dict[str, Any]:
    """通读原文抽出一份草稿：构建提示 → 调用模型 → 解析 → 校验 → 返回。

    调用模型 由调用方注入，签名是 提示 -> 文本；本函数不访问网络，也不写文件。
    本函数不验篇幅：正式路径走 抽取短篇草稿，评测样本节选与 harness 直接调本函数。
    """
    if not isinstance(原文, str):
        raise TypeError("原文必须是字符串")
    if not callable(调用模型):
        raise TypeError("调用模型 必须是可调用的函数")

    模型输出 = 解析模型输出(调用模型(构建抽取提示(原文)))
    草稿: dict[str, Any] = {
        "人物卡": [_人物卡(人物, 原文) for 人物 in _列表(模型输出, "人物")],
        "场景卡": [_场景卡(场景, 原文) for 场景 in _列表(模型输出, "场景")],
        "风格ID": {"草稿": _字符串(模型输出.get("风格ID"), "风格ID"), "确认状态": 未确认},
        "故事节拍": [_节拍(条, 原文) for 条 in _列表(模型输出, "故事节拍")],
        "无主线索": [_无主线索(条, 原文) for 条 in _列表(模型输出, "无主线索")],
    }
    _查名称唯一(草稿["人物卡"])
    return 草稿


def 未处理的无主线索(草稿: Mapping[str, Any]) -> list[dict[str, Any]]:
    """还没被主人跳过的无主线索。"""
    return [条 for 条 in 草稿.get("无主线索", []) if not 条.get("已跳过")]


def 整篇可出页(草稿: Mapping[str, Any]) -> bool:
    """整篇是否可出页。

    只看未处理的无主线索（契约第 46 行：只要还有未处理的无主线索，整篇不得出页）。
    未支持人物是另一种粒度，只拦该人物，由 人物可出页 现算，不在这里把整篇判死。
    """
    return not 未处理的无主线索(草稿)


def 未跳过的未支持(人物卡: Mapping[str, Any]) -> list[dict[str, Any]]:
    """该人物上还没被跳过的未支持条目。跳过标记记在每条上，互不覆盖。"""
    return [条 for 条 in 人物卡.get("未支持", []) if not 条.get("已跳过")]


def 人物可出页(人物卡: Mapping[str, Any]) -> bool:
    """该人物是否可出页：还有未跳过的未支持条目就不能出页。现算，不是快照。"""
    return not 未跳过的未支持(人物卡)


def 抽取短篇草稿(原文: str, 调用模型: 模型调用) -> dict[str, Any]:
    """正式入口：短篇须在 1 万到 2 万字之间，先验篇幅再抽取。

    评测样本是原文节选，不受这个门槛约束，所以 harness 与样本测试直接调 抽取草稿。
    """
    校验篇幅(原文)
    return 抽取草稿(原文, 调用模型)


def _人物卡(人物: Any, 原文: str) -> dict[str, Any]:
    """人物卡：一份人物身份，加上挂在其下的服装状态。身份只认六项字段。"""
    if not isinstance(人物, Mapping):
        raise 草稿非法("人物必须是对象")
    名称 = _字符串(人物.get("名称"), "人物.名称")
    if not 名称.strip():
        raise 草稿非法("人物卡必须有名称")
    起, 止 = _位置(人物, 原文, f"人物「{名称}」")
    未支持 = [_线索(条, f"人物「{名称}」的未支持", 原文) for 条 in _列表(人物, "未支持")]
    return {
        "名称": 名称,
        "人物身份": _身份(人物.get("身份"), 名称),
        "原文位置": {"起": 起, "止": 止},
        "服装状态列表": [
            _服装(服装, 原文, f"人物「{名称}」的服装") for 服装 in _列表(人物, "服装")
        ],
        "未支持": 未支持,
    }


def _身份(值: Any, 名称: str) -> dict[str, str]:
    """身份只认六项字段。没给的留空；变身后样貌、另一身份这类外来块一律丢掉，也不另存。"""
    if 值 is None:
        值 = {}
    if not isinstance(值, Mapping):
        raise 草稿非法(f"人物「{名称}」的身份必须是对象")
    身份 = {}
    for 字段 in 人物身份字段:
        原值 = 值.get(字段)
        if 原值 is None:
            身份[字段] = ""
        elif isinstance(原值, str):
            身份[字段] = 原值
        else:
            raise 草稿非法(f"人物「{名称}」的身份字段「{字段}」必须是字符串")
    return 身份


def _服装(服装: Any, 原文: str, 名字: str) -> dict[str, Any]:
    if not isinstance(服装, Mapping):
        raise 草稿非法(f"{名字}必须是对象")
    起, 止 = _位置(服装, 原文, 名字)
    return {
        "名称": _字符串(服装.get("名称"), f"{名字}.名称"),
        "描述": _字符串(服装.get("描述"), f"{名字}.描述"),
        "原文位置": {"起": 起, "止": 止},
        "确认状态": 未确认,
    }


def _场景卡(场景: Any, 原文: str) -> dict[str, Any]:
    if not isinstance(场景, Mapping):
        raise 草稿非法("场景必须是对象")
    名称 = _字符串(场景.get("名称"), "场景.名称")
    起, 止 = _位置(场景, 原文, f"场景「{名称}」")
    return {
        "名称": 名称,
        "建筑外观": _字符串(场景.get("建筑外观"), "场景.建筑外观"),
        "原文位置": {"起": 起, "止": 止},
        "确认状态": 未确认,
    }


def _节拍(条: Any, 原文: str) -> dict[str, Any]:
    if not isinstance(条, Mapping):
        raise 草稿非法("故事节拍必须是对象")
    起, 止 = _位置(条, 原文, "故事节拍")
    return {
        "顺序": _整数(条.get("顺序"), "故事节拍.顺序"),
        "摘要": _字符串(条.get("摘要"), "故事节拍.摘要"),
        "原文起": 起,
        "原文止": 止,
    }


def _线索(条: Any, 名字: str, 原文: str) -> dict[str, Any]:
    """一条未支持线索：类别必须落在契约的三类里，片段是原文里的原话。

    原文起止是可选线索，模型给得不对就留空，不影响判定。
    每条都自带 已跳过，抽取时一律 False；跳过标记由确认关卡按条写，互不覆盖。
    """
    if not isinstance(条, Mapping):
        raise 草稿非法(f"{名字}必须是对象")
    类别 = 条.get("类别")
    if 类别 not in 未支持类别:
        raise 草稿非法(f"{名字}的类别必须是 {未支持类别} 之一，当前为 {类别!r}")
    片段 = 条.get("片段", "")
    if not isinstance(片段, str):
        raise 草稿非法(f"{名字}的片段必须是字符串")
    起, 止 = _可选位置(条, 原文)
    return {"类别": 类别, "片段": 片段, "原文起": 起, "原文止": 止, "已跳过": False}


def _无主线索(条: Any, 原文: str) -> dict[str, Any]:
    """草稿上的一条无主线索：不写入任何人物卡，也不进引用记录。"""
    return _线索(条, "无主线索", 原文)


def _查名称唯一(卡表: list[dict[str, Any]]) -> None:
    已见: set[str] = set()
    for 卡 in 卡表:
        if 卡["名称"] in 已见:
            raise 名称重复(f"人物卡名称必须唯一，重复的名称：{卡['名称']}")
        已见.add(卡["名称"])


def _位置(来源: Mapping[str, Any], 原文: str, 名字: str) -> tuple[int, int]:
    起 = _整数(来源.get("原文起"), f"{名字}.原文起")
    止 = _整数(来源.get("原文止"), f"{名字}.原文止")
    if 起 < 0 or 止 < 起 or 止 > len(原文):
        raise 草稿非法(f"{名字}的原文位置越界：{起}..{止}，原文长 {len(原文)}")
    return 起, 止


def _可选位置(来源: Mapping[str, Any], 原文: str) -> tuple[int | None, int | None]:
    起 = 来源.get("原文起")
    止 = 来源.get("原文止")
    if isinstance(起, int) and isinstance(止, int) and not isinstance(起, bool) and not isinstance(止, bool):
        if 0 <= 起 <= 止 <= len(原文):
            return 起, 止
    return None, None


def _列表(模型输出: Mapping[str, Any], 键: str) -> list[Any]:
    值 = 模型输出.get(键, [])
    if 值 is None:
        return []
    if not isinstance(值, list):
        raise 草稿非法(f"{键}必须是列表")
    return 值


def _字符串(值: Any, 名字: str) -> str:
    if 值 is None:
        return ""
    if not isinstance(值, str):
        raise 草稿非法(f"{名字}必须是字符串")
    return 值


def _整数(值: Any, 名字: str) -> int:
    if isinstance(值, bool) or not isinstance(值, int):
        raise 草稿非法(f"{名字}必须是整数")
    return 值


def _去代码围栏(文本: str) -> str:
    净 = 文本.strip()
    if not 净.startswith("```"):
        return 净
    _, _, 余下 = 净.partition("\n")
    结尾 = 余下.rfind("```")
    if 结尾 != -1:
        余下 = 余下[:结尾]
    return 余下.strip()
