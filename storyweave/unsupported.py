"""把原文里的常见字样位置整理成一段提示文本，交给文本模型参考。

DEC-7：年龄阶段切换、伪装成他人与变身由文本模型通读原文判定。
本模块只找出常见字样的位置并拼成提示，不拍板任何人物的未支持判定，也不产出
「命中」这类结论字段；字样命中与已知答案冲突时，以模型的判定为准。
"""

from __future__ import annotations

import re

变身 = "变身"
伪装成他人 = "伪装成他人"
年龄阶段切换 = "年龄阶段切换"

未支持类别: tuple[str, ...] = (变身, 伪装成他人, 年龄阶段切换)

# 提示字样表：(类别, 正则)。只用来找位置；算不算未支持由文本模型通读全文判断。
提示字样表: tuple[tuple[str, str], ...] = (
    # 变身：人物整体换成别的形态或物种。
    (变身, r"变身"),
    (变身, r"摇身一变"),
    (变身, r"(?:现|显|露|变回)(?:出|了)?原形"),
    (
        变身,
        r"变[成为作](?:一|二|三|几)?(?:只|条|头|匹|尾|群)?[^，。；！？、\s]{0,8}?"
        r"(?:兽|狼|蛇|龙|鸟|狐|鱼|猫|狗|虎|豹|虫|妖|怪|魔|鬼)",
    ),
    # 伪装成他人：人物顶着别人的身份或面貌出现。
    (伪装成他人, r"伪装成"),
    (伪装成他人, r"假扮|(?<!假)扮(?:成|作)"),
    (伪装成他人, r"冒充"),
    (伪装成他人, r"易容"),
    (伪装成他人, r"化装成"),
    (伪装成他人, r"换了?一(?:副|张|个)(?:脸|面孔|模样|长相)"),
    (伪装成他人, r"顶着[^，。；！？\s]{0,8}的(?:脸|面孔|身份|名字|模样)"),
    # 年龄阶段切换：跨过一个年龄阶段，不是长了一岁。
    (
        年龄阶段切换,
        r"(?:多年|数年|若干年|十几年|几十年|十[一二三四五六七八九]?年|"
        r"[二三四五六七八九]十(?:多|余)?年|[一二三四五六七八九]?百(?:多|余)?年|"
        r"[1-9][0-9]+(?:多|余)?年)(?:之?后|以后)",
    ),
    (年龄阶段切换, r"长大(?:成人|之?后|以后)"),
    (
        年龄阶段切换,
        r"长成(?:了)?(?:一个|一名|一位)?(?:少年|少女|青年|大人|成年人|小伙子|大姑娘|姑娘)",
    ),
    (年龄阶段切换, r"成年(?:之?后|以后)"),
    (年龄阶段切换, r"(?:步入|人到|已是|到了|进入)(?:中年|老年)"),
    (
        年龄阶段切换,
        r"(?:变)?成了(?:一个|一名|一位|个)?(?:中年|老年|少年|少女|青年|大人|成年人)",
    ),
)


def 找字样位置(原文: str) -> list[dict[str, object]]:
    """找出常见字样的位置。每条只有类别、字样和位置，不含任何判定结论。"""
    if not isinstance(原文, str):
        raise TypeError("原文必须是字符串")
    位置表: list[dict[str, object]] = []
    已见: set[tuple[str, int, int]] = set()
    for 类别, 正则 in 提示字样表:
        for 匹配 in re.finditer(正则, 原文):
            键 = (类别, 匹配.start(), 匹配.end())
            if 键 in 已见:
                continue
            已见.add(键)
            位置表.append({"类别": 类别, "字样": 匹配.group(0), "位置": 匹配.start()})
    位置表.sort(key=lambda 条: (条["位置"], 条["类别"], 条["字样"]))
    return 位置表


def 构建未支持提示(原文: str) -> str:
    """把常见字样的位置拼成一段提示文本，供抽取提示参考。

    提示只是线索：有字样不等于未支持，没字样也不等于没有。判定由文本模型做。
    """
    位置表 = 找字样位置(原文)
    行 = [
        "以下是原文中出现的常见字样位置，仅供参考，不构成判定：",
        "- 这些字样可能对应年龄阶段切换、伪装成他人或变身，也可能只是普通换装或玩笑扮相；",
        "- 以你通读全文后的判断为准：不要因为有字样就判是，也不要因为没字样就判否。",
    ]
    if not 位置表:
        行.append("（未发现任何常见字样。）")
    for 条 in 位置表:
        行.append(f"- 原文第 {条['位置']} 字附近：「{条['字样']}」（{条['类别']}类字样）")
    return "\n".join(行)
