"""ITEM-1：未支持判定按人物给出、与抽取同出一趟；正则规则表降级为提示（DEC-7）。

还覆盖 P1-2：未支持状态下身份字段只保留进入该状态之前的样貌。
全部用例用假模型，不访问网络。
"""

import json

import pytest

import storyweave.unsupported as 提示模块
from storyweave import (
    人物可出页,
    人物身份字段,
    抽取草稿,
    整篇可出页,
    未跳过的未支持,
    构建抽取提示,
    构建未支持提示,
    草稿非法,
    找字样位置,
    未支持类别,
)

原文样本 = "小禾坐在廊下剥豆子。她摇身一变，成了一头狼。多年以后，她回到了村子。"
变后哨兵 = {
    "脸型": "变后脸型哨兵狼脸",
    "发型与发色": "变后发型哨兵灰毛",
    "眼": "变后眼哨兵竖瞳",
    "显著特征": "变后特征哨兵獠牙",
    "年龄": "变后年龄哨兵十六",
    "体态": "变后体态哨兵四足",
}


def _人物(名称, **覆盖):
    人物 = {
        "名称": 名称,
        "身份": dict.fromkeys(人物身份字段, ""),
        "原文起": 0,
        "原文止": len(原文样本),
        "服装": [],
        "未支持": [],
    }
    人物.update(覆盖)
    return 人物


def _模型(人物=(), 无主线索=()):
    def 调用模型(提示):
        return json.dumps(
            {
                "人物": list(人物),
                "场景": [],
                "风格ID": "水墨",
                "故事节拍": [],
                "无主线索": list(无主线索),
            },
            ensure_ascii=False,
        )

    return 调用模型


def test_找字样位置只给位置不给判定():
    位置表 = 找字样位置(原文样本)
    assert 位置表, "样本里有常见字样"
    for 条 in 位置表:
        assert set(条) == {"类别", "字样", "位置"}
        assert 条["类别"] in 未支持类别
        assert 原文样本[条["位置"] : 条["位置"] + len(条["字样"])] == 条["字样"]

    字样集 = {条["字样"] for 条 in 位置表}
    assert "摇身一变" in 字样集
    assert "多年以后" in 字样集


def test_规则表降级为提示不再拍板():
    """模块只提供提示文本，不再提供「扫描命中」和「归属到某人物」这两件拍板能力。"""
    assert not hasattr(提示模块, "扫描")
    assert not hasattr(提示模块, "命中该人物")
    assert isinstance(构建未支持提示(原文样本), str)


def test_提示文本带位置与字样并说明不作判定():
    提示 = 构建未支持提示(原文样本)
    assert "摇身一变" in 提示
    assert "多年以后" in 提示
    assert str(原文样本.index("摇身一变")) in 提示
    assert "不构成判定" in 提示
    assert "以你通读全文后的判断为准" in 提示


def test_没有常见字样时提示文本也说明情况():
    提示 = 构建未支持提示("风从山那边吹过来，带着一点湿气。")
    assert "未发现任何常见字样" in 提示


def test_提示文本能拼进抽取提示():
    提示 = 构建抽取提示(原文样本)
    assert 原文样本 in 提示
    assert "摇身一变" in 提示
    assert "仅供参考" in 提示


def test_未支持判定按人物给出且不靠字样拍板():
    """原文有「摇身一变」，但模型判否：结果跟模型的判定走。"""
    草稿 = 抽取草稿(原文样本, _模型(人物=[_人物("小禾")]))
    卡 = 草稿["人物卡"][0]
    assert 卡["未支持"] == []
    assert 人物可出页(卡) is True
    assert 草稿["无主线索"] == []


def test_模型判是时记下类别与片段():
    线索 = {"类别": "变身", "片段": "摇身一变"}
    草稿 = 抽取草稿(原文样本, _模型(人物=[_人物("小禾", 未支持=[线索])]))
    卡 = 草稿["人物卡"][0]
    assert 人物可出页(卡) is False
    assert [条["类别"] for 条 in 卡["未支持"]] == ["变身"]
    assert 卡["未支持"][0]["片段"] == "摇身一变"
    assert 卡["未支持"][0]["原文起"] is None
    assert 草稿["无主线索"] == []
    assert 整篇可出页(草稿) is True, "未支持人物只拦该人物，无主线索才拦整篇"


def test_三类未支持都能按人物给出():
    for 类别 in 未支持类别:
        草稿 = 抽取草稿(原文样本, _模型(人物=[_人物("小禾", 未支持=[{"类别": 类别, "片段": ""}])]))
        卡 = 草稿["人物卡"][0]
        assert [条["类别"] for 条 in 卡["未支持"]] == [类别]
        assert 人物可出页(卡) is False


def test_未知未支持类别被拒绝():
    with pytest.raises(草稿非法):
        抽取草稿(原文样本, _模型(人物=[_人物("小禾", 未支持=[{"类别": "换装", "片段": ""}])]))


def test_另一个人物不受影响():
    草稿 = 抽取草稿(
        原文样本,
        _模型(人物=[_人物("小禾", 未支持=[{"类别": "变身", "片段": "摇身一变"}]), _人物("阿圆")]),
    )
    小禾卡, 阿圆卡 = 草稿["人物卡"]
    assert 人物可出页(小禾卡) is False
    assert 未跳过的未支持(小禾卡) == [{"类别": "变身", "片段": "摇身一变", "原文起": None, "原文止": None, "已跳过": False}]
    assert 阿圆卡["未支持"] == []
    assert 人物可出页(阿圆卡) is True


def test_未支持不写进人物身份也不写进服装状态():
    草稿 = 抽取草稿(
        原文样本,
        _模型(
            人物=[
                _人物(
                    "小禾",
                    未支持=[{"类别": "变身", "片段": "摇身一变"}],
                    服装=[{"名称": "校服", "描述": "深蓝校服", "原文起": 0, "原文止": 2}],
                )
            ]
        ),
    )
    卡 = 草稿["人物卡"][0]
    assert set(卡["人物身份"]) == set(人物身份字段)
    身份文 = json.dumps(卡["人物身份"], ensure_ascii=False)
    assert "摇身一变" not in 身份文
    assert "变身" not in 身份文
    assert set(卡["服装状态列表"][0]) == {"名称", "描述", "原文位置", "确认状态"}
    assert "变身" not in json.dumps(卡["服装状态列表"], ensure_ascii=False)


def test_未支持人物的身份字段不承载变身后的样貌():
    """P1-2：模型把变后样貌单独给出时，身份字段留空，变后描述不进身份。"""
    草稿 = 抽取草稿(
        原文样本,
        _模型(
            人物=[
                _人物(
                    "小禾",
                    未支持=[{"类别": "变身", "片段": "摇身一变"}],
                    变身后样貌=变后哨兵,
                )
            ]
        ),
    )
    卡 = 草稿["人物卡"][0]
    assert 人物可出页(卡) is False
    assert 卡["人物身份"] == dict.fromkeys(人物身份字段, "")
    for 哨兵 in 变后哨兵.values():
        assert 哨兵 not in json.dumps(草稿, ensure_ascii=False)


def test_变后样貌不并入身份也不另存():
    草稿 = 抽取草稿(
        原文样本,
        _模型(
            人物=[
                _人物(
                    "小禾",
                    身份={"脸型": "鹅卵脸", "发型与发色": "短发", "眼": "细长", "显著特征": "左眉疤", "年龄": "十七", "体态": "清瘦"},
                    未支持=[{"类别": "变身", "片段": "摇身一变"}],
                    变身后样貌=变后哨兵,
                    另一身份=变后哨兵,
                )
            ]
        ),
    )
    卡 = 草稿["人物卡"][0]
    assert 卡["人物身份"] == {
        "脸型": "鹅卵脸",
        "发型与发色": "短发",
        "眼": "细长",
        "显著特征": "左眉疤",
        "年龄": "十七",
        "体态": "清瘦",
    }
    全文 = json.dumps(草稿, ensure_ascii=False)
    for 哨兵 in 变后哨兵.values():
        assert 哨兵 not in 全文
    assert set(卡) == {"名称", "人物身份", "原文位置", "服装状态列表", "未支持"}


def test_原文没给未支持前的样貌时身份留空且不判抽取失败():
    输出 = {
        "人物": [{"名称": "小禾", "原文起": 0, "原文止": 3, "服装": [], "未支持": [{"类别": "年龄阶段切换", "片段": "多年以后"}]}],
        "场景": [],
        "风格ID": "水墨",
        "故事节拍": [],
        "无主线索": [],
    }
    草稿 = 抽取草稿(原文样本, _模型(人物=输出["人物"]))
    卡 = 草稿["人物卡"][0]
    assert 卡["人物身份"] == dict.fromkeys(人物身份字段, "")
    assert 人物可出页(卡) is False
    assert 整篇可出页(草稿) is True


def test_未支持但原文给了先前样貌时身份保留先前样貌():
    先前 = {"脸型": "圆脸", "发型与发色": "短发", "眼": "细长", "显著特征": "左眉疤", "年龄": "十七", "体态": "清瘦"}
    草稿 = 抽取草稿(
        原文样本,
        _模型(人物=[_人物("小禾", 身份=dict(先前), 未支持=[{"类别": "变身", "片段": "摇身一变"}])]),
    )
    卡 = 草稿["人物卡"][0]
    assert 卡["人物身份"] == 先前
    assert 人物可出页(卡) is False
