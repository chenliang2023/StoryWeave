def test_写页剧本不改档案():
    档案 = _全确认档案()
    快照 = copy.deepcopy(档案)

    页剧本 = 写页剧本(
        档案,
        _草稿(),
        _调用(
            [
                _页(节拍顺序=(1,), 引用记录=_引用(服装状态=("服装:阿明:0",))),
                _页(节拍顺序=(2,), 引用记录=_引用(服装状态=("服装:阿明:0",))),
            ]
        ),
    )

    assert 引用次数(页剧本, "服装:阿明:0") == 2
    assert 要求参考图(页剧本, "服装:阿明:0") is True
    assert 档案 == 快照


def test_节拍快照是拷贝不被草稿带跑():
    草稿 = _草稿()
    页剧本 = 写页剧本(_全确认档案(), 草稿, _调用([_页()]))

    草稿["故事节拍"][0]["摘要"] = "改过的摘要"

    assert 页剧本["节拍快照"][0]["摘要"] == "阿明推开院门"
    assert len(页剧本["节拍快照"]) == 3


def test_节拍冻结后改动使页剧本失效():
    草稿 = _草稿()
    页剧本 = 写页剧本(_全确认档案(), 草稿, _调用([_页()]))
    assert 节拍已改(页剧本, 草稿) is False
    assert 页剧本已失效(页剧本, 草稿) is False

    草稿["故事节拍"][2]["摘要"] = "阿禾把柴塞进灶膛"

    assert 节拍已改(页剧本, 草稿) is True
    assert 页剧本已失效(页剧本, 草稿) is True


def test_档案确认状态不影响已生成的页剧本的失效判定():
    草稿 = _草稿()
    档案 = _全确认档案()
    页剧本 = 写页剧本(档案, 草稿, _调用([_页()]))

    改服装状态(档案, "服装:阿明:0", "青布短打")

    assert 页剧本已失效(页剧本, 草稿) is False
