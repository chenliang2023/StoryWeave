def test_落实带图要求对不上项ID时报错():
    """档案的项 ID 已经对不上页剧本的引用时，不许静默放掉带图要求。"""
    档案 = _全确认档案()
    页剧本 = 写页剧本(档案, _草稿(), _调用(_四页()))
    档案["人物卡"][0]["服装状态列表"] = []

    with pytest.raises(页剧本非法):
        落实带图要求(档案, 页剧本)
