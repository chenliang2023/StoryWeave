"""ITEM-1 · P1-1：无从归属到人物的未支持线索记为无主线索，并拦住整篇出页。

全部用例用假模型，不访问网络。
"""

import json

import pytest

from storyweave import (
    人物可出页,
    抽取草稿,
    整篇可出页,
    未处理的无主线索,
    未跳过的未支持,
    草稿非法,
)

原文 = "有人摇身一变，成了狼。"


def _模型(人物=(), 无主线索=()):
    def 调用模型(提示):
        return json.dumps(
            {
                "人物": list(人物),
                "场景": [],
                "风格ID": "水墨",
                "故事节拍": [],
                "无主线索": list(无主线索),
            },
            ensure_ascii=False,
        )

    return 调用模型


def _人物卡(名称, 未支持=()):
    return {
        "名称": 名称,
        "身份": {"脸型": "鹅卵脸", "发型与发色": "", "眼": "", "显著特征": "", "年龄": "", "体态": ""},
        "原文起": 0,
        "原文止": len(原文),
        "服装": [],
        "未支持": list(未支持),
    }


def test_无从归属的线索记为无主线索并拦住整篇出页():
    草稿 = 抽取草稿(原文, _模型(无主线索=[{"类别": "变身", "片段": 原文}]))
    线索 = 草稿["无主线索"]
    assert len(线索) == 1
    assert set(线索[0]) == {"类别", "片段", "原文起", "原文止", "已跳过"}
    assert 线索[0]["类别"] == "变身"
    assert 线索[0]["片段"] == 原文
    assert 线索[0]["已跳过"] is False
    assert 整篇可出页(草稿) is False, "还有未处理的无主线索时整篇不得出页"


def test_无主线索不写入任何人物卡():
    草稿 = 抽取草稿(原文, _模型(人物=[_人物卡("阿圆")], 无主线索=[{"类别": "变身", "片段": 原文}]))
    卡 = 草稿["人物卡"][0]
    assert 卡["未支持"] == []
    assert 人物可出页(卡) is True, "线索不归这个人物"
    assert 整篇可出页(草稿) is False, "但整篇仍然不得出页"
    assert 原文 not in json.dumps(卡, ensure_ascii=False)


def test_不得为无主线索新建人物卡():
    草稿 = 抽取草稿(原文, _模型(无主线索=[{"类别": "变身", "片段": 原文}]))
    assert 草稿["人物卡"] == []
    assert "有人" not in {卡["名称"] for 卡 in 草稿["人物卡"]}


def test_没有无主线索时整篇可出页():
    草稿 = 抽取草稿(原文, _模型(人物=[_人物卡("阿圆")]))
    assert 草稿["无主线索"] == []
    assert 未处理的无主线索(草稿) == []
    assert 整篇可出页(草稿) is True


def test_无主线索被跳过之后整篇才可出页():
    草稿 = 抽取草稿(原文, _模型(人物=[_人物卡("阿圆")], 无主线索=[{"类别": "变身", "片段": 原文}]))
    assert 整篇可出页(草稿) is False

    草稿["无主线索"][0]["已跳过"] = True
    assert 未处理的无主线索(草稿) == []
    assert 整篇可出页(草稿) is True


def test_多条无主线索只要有一条未处理就拦住整篇():
    草稿 = 抽取草稿(
        原文,
        _模型(
            无主线索=[
                {"类别": "变身", "片段": 原文},
                {"类别": "年龄阶段切换", "片段": "多年以后"},
            ]
        ),
    )
    assert 整篇可出页(草稿) is False
    草稿["无主线索"][0]["已跳过"] = True
    assert 整篇可出页(草稿) is False, "还剩一条未处理"


def test_无主线索类别受契约约束():
    with pytest.raises(草稿非法):
        抽取草稿(原文, _模型(无主线索=[{"类别": "换装", "片段": 原文}]))


def test_提示里有字样但模型判否时不产生无主线索():
    """正则只作提示：样本「她扮成鬼脸逗他笑」有「扮成」字样，结果仍跟已知答案走。"""
    样本 = "她扮成鬼脸逗他笑。"
    输出 = {
        "人物": [
            {
                "名称": "她",
                "身份": dict.fromkeys(("脸型", "发型与发色", "眼", "显著特征", "年龄", "体态"), ""),
                "原文起": 0,
                "原文止": len(样本),
                "服装": [],
                "未支持": [],
            }
        ],
        "场景": [],
        "风格ID": "水墨",
        "故事节拍": [],
        "无主线索": [],
    }
    草稿 = 抽取草稿(样本, _模型(人物=输出["人物"]))
    assert 草稿["无主线索"] == []
    assert 草稿["人物卡"][0]["未支持"] == []
    assert 整篇可出页(草稿) is True


def test_未支持人物只影响该人物不把整篇判死():
    """契约两种粒度分开：无主线索拦整篇，未支持人物只拦该人物。"""
    草稿 = 抽取草稿(
        原文,
        _模型(
            人物=[
                _人物卡("阿圆", 未支持=[{"类别": "变身", "片段": "摇身一变"}]),
                _人物卡("阿禾"),
            ]
        ),
    )
    阿圆卡, 阿禾卡 = 草稿["人物卡"]
    assert 人物可出页(阿圆卡) is False
    assert 人物可出页(阿禾卡) is True
    assert 草稿["无主线索"] == []
    assert 整篇可出页(草稿) is True, "没有未处理的无主线索时整篇不被人物判定拖死"


def test_未支持人物条目各带已跳过且互不覆盖():
    """契约第 68 行：每条无主线索、每个未支持人物各记一条跳过标记，互不覆盖。"""
    草稿 = 抽取草稿(
        原文,
        _模型(
            人物=[
                _人物卡(
                    "阿圆",
                    未支持=[
                        {"类别": "变身", "片段": "摇身一变"},
                        {"类别": "年龄阶段切换", "片段": "多年以后"},
                    ],
                )
            ],
            无主线索=[{"类别": "变身", "片段": 原文}],
        ),
    )
    卡 = 草稿["人物卡"][0]
    assert len(卡["未支持"]) == 2
    for 条 in 卡["未支持"]:
        assert 条["已跳过"] is False
        assert set(条) == {"类别", "片段", "原文起", "原文止", "已跳过"}
    assert len(未跳过的未支持(卡)) == 2
    assert 人物可出页(卡) is False

    卡["未支持"][0]["已跳过"] = True
    assert len(未跳过的未支持(卡)) == 1, "只跳过其中一条，另一条不受影响"
    assert 人物可出页(卡) is False
    assert 草稿["无主线索"][0]["已跳过"] is False, "人物条目的跳过不覆盖无主线索"

    卡["未支持"][1]["已跳过"] = True
    assert 未跳过的未支持(卡) == []
    assert 人物可出页(卡) is True
    assert 整篇可出页(草稿) is False, "无主线索仍未处理"
