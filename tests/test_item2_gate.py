    草稿 = _草稿(无主线索=[{"类别": "变身", "片段": "有人摇身一变，成了狼。"}])
    档案 = _全确认(建档案(草稿))
    assert 整篇出页检查(档案, 草稿)["可出页"] is False
    assert 人物出页检查(档案, 草稿, "阿禾")["可出页"] is True


