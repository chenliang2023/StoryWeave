"""ITEM-2 · 确认关卡的出页检查与跳过标记。

契约把两种粒度分开：未处理的无主线索拦整篇；未支持的未跳过人物只拦该人物。
跳过标记记在草稿上，不算档案项。全部离线。
"""

import json

import pytest

from storyweave import 抽取草稿
from storyweave.archive import (
    建档案,
    改人物身份,
    改风格ID,
    确认人物卡,
    确认参考图,
    确认场景卡,
    确认风格ID,
    附参考图,
    已确认,
)
from storyweave.gate import 关卡非法, 人物出页检查, 跳过无主线索, 跳过未支持, 整篇出页检查

原文 = "阿明推开院门。他摇身一变，皮毛从手背上冒了出来。有人摇身一变，成了狼。"
假图片 = b"\x89PNG\r\n\x1a\nfake-image-bytes"


def _模型输出(无主线索=(), 阿明未支持=()):
    return {
        "人物": [
            {
                "名称": "阿明",
                "身份": {
                    "脸型": "鹅卵脸",
                    "发型与发色": "短黑发",
                    "眼": "细长眼",
                    "显著特征": "左眉疤",
                    "年龄": "十七",
                    "体态": "清瘦",
                },
                "原文起": 0,
                "原文止": 6,
                "服装": [{"名称": "旧棉袄", "描述": "灰布旧棉袄", "原文起": 0, "原文止": 3}],
                "未支持": list(阿明未支持),
            },
            {
                "名称": "阿禾",
                "身份": dict.fromkeys(
                    ("脸型", "发型与发色", "眼", "显著特征", "年龄", "体态"), "阿禾的样貌"
                ),
                "原文起": 7,
                "原文止": 12,
                "服装": [],
                "未支持": [],
            },
        ],
        "场景": [{"名称": "院子", "建筑外观": "青砖院墙", "原文起": 0, "原文止": 4}],
        "风格ID": "水墨",
        "故事节拍": [],
        "无主线索": list(无主线索),
    }


def _草稿(无主线索=(), 阿明未支持=()):
    return 抽取草稿(原文, lambda 提示: json.dumps(_模型输出(无主线索, 阿明未支持), ensure_ascii=False))


def _全确认(档案):
    确认人物卡(档案, "阿明")
    确认人物卡(档案, "阿禾")
    确认场景卡(档案, "场景:院子")
    确认风格ID(档案)
    附参考图(档案, "身份:阿明", 假图片)
    确认参考图(档案, "身份:阿明")
    附参考图(档案, "身份:阿禾", 假图片)
    确认参考图(档案, "身份:阿禾")
    附参考图(档案, "风格:水墨", 假图片)
    确认参考图(档案, "风格:水墨")
    return 档案


# ---------- 整篇出页检查 ----------


def test_全未确认时整篇出页被拒且理由逐项列出():
    档案 = 建档案(_草稿())
    结果 = 整篇出页检查(档案, _草稿())
    assert 结果["可出页"] is False
    理由 = " | ".join(结果["拒绝理由"])
    assert "身份:阿明" in 理由
    assert "服装:阿明:0" in 理由
    assert "场景:院子" in 理由
    assert "风格:水墨" in 理由


def test_全部确认且身份与风格图已确认时可出页():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is True
    assert 结果["拒绝理由"] == []


def test_缺已确认的身份参考图时被拒():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
    档案["人物卡"][0]["身份参考图"]["确认状态"] = "未确认"
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is False
    assert any("身份:阿明" in 理由 and "参考图" in 理由 for 理由 in 结果["拒绝理由"])


def test_缺已确认的风格样张时被拒():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
    档案["风格ID"]["样张"] = None
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is False
    assert any("风格:水墨" in 理由 and "样张" in 理由 for 理由 in 结果["拒绝理由"])


def test_服装状态与场景卡首次确认允许暂无参考图():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
    assert 档案["人物卡"][0]["服装状态列表"][0]["参考图"] is None
    assert 档案["场景卡"][0]["参考图"] is None
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is True, "带图要求留到按引用记录判定，本步不因缺图拦"


def test_修改后未再确认时整篇被拒():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
    改风格ID(档案, "厚涂")
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is False
    assert any("风格" in 理由 for 理由 in 结果["拒绝理由"])


def test_改身份后整篇被拒直到重新确认():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
    改人物身份(档案, "阿明", {"脸型": "方脸"})
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is False
    理由 = " | ".join(结果["拒绝理由"])
    assert "身份:阿明" in 理由
    assert "服装:阿明:0" in 理由, "身份改了，其下服装也退回未确认"


# ---------- 无主线索拦整篇 ----------


def test_有未处理的无主线索时整篇被拒():
    草稿 = _草稿(无主线索=[{"类别": "变身", "片段": "有人摇身一变，成了狼。"}])
    档案 = _全确认(建档案(草稿))
    结果 = 整篇出页检查(档案, 草稿)
    assert 结果["可出页"] is False
    assert any("无主线索" in 理由 for 理由 in 结果["拒绝理由"])


def test_跳过无主线索之后整篇才可出页():
    草稿 = _草稿(无主线索=[{"类别": "变身", "片段": "有人摇身一变，成了狼。"}])
    档案 = _全确认(建档案(草稿))
    assert 整篇出页检查(档案, 草稿)["可出页"] is False

    跳过无主线索(草稿, 0)
    assert 草稿["无主线索"][0]["已跳过"] is True
    assert 整篇出页检查(档案, 草稿)["可出页"] is True


def test_跳过一个无主线索不影响另一条():
    草稿 = _草稿(
        无主线索=[
            {"类别": "变身", "片段": "有人摇身一变，成了狼。"},
            {"类别": "年龄阶段切换", "片段": "多年以后"},
        ]
    )
    档案 = _全确认(建档案(草稿))
    跳过无主线索(草稿, 0)
    assert 整篇出页检查(档案, 草稿)["可出页"] is False, "还剩一条未处理"
    跳过无主线索(草稿, 1)
    assert 整篇出页检查(档案, 草稿)["可出页"] is True


def test_跳过标记记在草稿上不算档案项():
    草稿 = _草稿(无主线索=[{"类别": "变身", "片段": "有人摇身一变，成了狼。"}])
    档案 = _全确认(建档案(草稿))
    跳过无主线索(草稿, 0)
    文 = json.dumps(档案, ensure_ascii=False, default=lambda 值: f"<{len(值)}字节>")
    assert "已跳过" not in 文, "跳过标记不进档案"
    assert "无主线索" not in 文


def test_跳过无主线索序号越界时拒绝():
    草稿 = _草稿()
    with pytest.raises(关卡非法):
        跳过无主线索(草稿, 0)
    with pytest.raises(关卡非法):
        跳过无主线索(草稿, -1)


# ---------- 未支持人物只拦该人物 ----------


def test_未支持人物未跳过时该人物被拒其他人不受影响():
    草稿 = _草稿(阿明未支持=[{"类别": "变身", "片段": "摇身一变"}])
    档案 = _全确认(建档案(草稿))

    阿明 = 人物出页检查(档案, 草稿, "阿明")
    阿禾 = 人物出页检查(档案, 草稿, "阿禾")
    assert 阿明["可出页"] is False
    assert any("未支持" in 理由 for 理由 in 阿明["拒绝理由"])
    assert 阿禾["可出页"] is True
    assert 整篇出页检查(档案, 草稿)["可出页"] is True, "未支持人物不把整篇判死"


def test_跳过未支持之后该人物通过():
    草稿 = _草稿(阿明未支持=[{"类别": "变身", "片段": "摇身一变"}])
    档案 = _全确认(建档案(草稿))
    跳过未支持(草稿, "阿明", 0)
    assert 草稿["人物卡"][0]["未支持"][0]["已跳过"] is True
    assert 人物出页检查(档案, 草稿, "阿明")["可出页"] is True


def test_跳过一个未支持不影响另一个人的未支持():
    草稿 = _草稿(
        阿明未支持=[
            {"类别": "变身", "片段": "摇身一变"},
            {"类别": "年龄阶段切换", "片段": "多年以后"},
        ]
    )
    档案 = _全确认(建档案(草稿))
    跳过未支持(草稿, "阿明", 0)
    assert 人物出页检查(档案, 草稿, "阿明")["可出页"] is False, "还剩一条未跳过"
    跳过未支持(草稿, "阿明", 1)
    assert 人物出页检查(档案, 草稿, "阿明")["可出页"] is True


def test_跳过未支持序号越界或人物不存在时拒绝():
    草稿 = _草稿(阿明未支持=[{"类别": "变身", "片段": "摇身一变"}])
    with pytest.raises(关卡非法):
        跳过未支持(草稿, "阿明", 5)
    with pytest.raises(关卡非法):
        跳过未支持(草稿, "没有这个人", 0)


# ---------- 人物出页检查只看该人物 ----------


def test_人物出页检查按该人物自己的身份与服装():
    草稿 = _草稿()
    档案 = _全确认(建档案(草稿))
